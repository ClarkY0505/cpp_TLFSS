section .text

global tlss_avx2_memcpy_5

tlss_avx2_memcpy_5:

    ; ------------------------------------------------------------
    ; System V AMD64 ABI
    ;
    ; rdi = dst
    ; rsi = src
    ; rdx = size
    ;
    ; rax = return value
    ; ------------------------------------------------------------

    mov rax, rdi
    ; memcpy 返回原始 dst


    ; ============================================================
    ; 0 ~ 15 B
    ; ============================================================

    cmp rdx, 16
    jb .small15


    ; ============================================================
    ; 16 ~ 31 B
    ; ============================================================

    cmp rdx, 32
    jb .size16_31


    ; ============================================================
    ; 32 ~ 63 B
    ; ============================================================

    cmp rdx, 64
    jb .size32_63


    ; ============================================================
    ; 64 ~ 127 B
    ; ============================================================

    cmp rdx, 128
    jb .size64_127


    ; ============================================================
    ; 128 ~ 255 B
    ; ============================================================

    cmp rdx, 256
    jb .size128_255


    ; ============================================================
    ; 256 ~ 511 B
    ;
    ; 搬一个完整 256B block，
    ; 剩余部分交给原有 <256B tail。
    ; ============================================================

    cmp rdx, 512
    jb .copy256_once


    ; ============================================================
    ; >= 512 B
    ;
    ; V5 main loop:
    ;
    ; 16 × YMM
    ; 16 × 32B
    ; = 512B / iteration
    ;
    ; 到这里已经保证 rdx >= 512，
    ; 因此使用 bottom-tested loop。
    ; ============================================================

.loop512:

    ; ------------------------------------------------------------
    ; Load 512B
    ; ------------------------------------------------------------

    vmovdqu ymm0,  [rsi]
    vmovdqu ymm1,  [rsi + 32]
    vmovdqu ymm2,  [rsi + 64]
    vmovdqu ymm3,  [rsi + 96]

    vmovdqu ymm4,  [rsi + 128]
    vmovdqu ymm5,  [rsi + 160]
    vmovdqu ymm6,  [rsi + 192]
    vmovdqu ymm7,  [rsi + 224]

    vmovdqu ymm8,  [rsi + 256]
    vmovdqu ymm9,  [rsi + 288]
    vmovdqu ymm10, [rsi + 320]
    vmovdqu ymm11, [rsi + 352]

    vmovdqu ymm12, [rsi + 384]
    vmovdqu ymm13, [rsi + 416]
    vmovdqu ymm14, [rsi + 448]
    vmovdqu ymm15, [rsi + 480]


    ; ------------------------------------------------------------
    ; Store 512B
    ; ------------------------------------------------------------

    vmovdqu [rdi],       ymm0
    vmovdqu [rdi + 32],  ymm1
    vmovdqu [rdi + 64],  ymm2
    vmovdqu [rdi + 96],  ymm3

    vmovdqu [rdi + 128], ymm4
    vmovdqu [rdi + 160], ymm5
    vmovdqu [rdi + 192], ymm6
    vmovdqu [rdi + 224], ymm7

    vmovdqu [rdi + 256], ymm8
    vmovdqu [rdi + 288], ymm9
    vmovdqu [rdi + 320], ymm10
    vmovdqu [rdi + 352], ymm11

    vmovdqu [rdi + 384], ymm12
    vmovdqu [rdi + 416], ymm13
    vmovdqu [rdi + 448], ymm14
    vmovdqu [rdi + 480], ymm15


    ; ------------------------------------------------------------
    ; Advance 512B
    ; ------------------------------------------------------------

    add rsi, 512
    add rdi, 512
    sub rdx, 512


    ; ------------------------------------------------------------
    ; Remaining >=512B ?
    ; ------------------------------------------------------------

    cmp rdx, 512
    jae .loop512


    ; ============================================================
    ; 从 loop512 出来之后：
    ;
    ; 0 <= rdx <= 511
    ;
    ; 如果还有 >=256B，
    ; 额外搬一次 256B。
    ; ============================================================

    cmp rdx, 256
    jae .copy256_once

    ; 否则直接处理 <256B tail
    jmp .tail_after_avx


; ================================================================
; Copy exactly one 256B block
;
; 这个路径有两个入口：
;
; 1. 初始 size = 256 ~ 511
; 2. loop512 之后剩余 256 ~ 511
;
; 完成后：
;
; rdx < 256
;
; 然后进入 tail。
; ================================================================

.copy256_once:

    ; ------------------------------------------------------------
    ; Load 256B
    ; ------------------------------------------------------------

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + 32]
    vmovdqu ymm2, [rsi + 64]
    vmovdqu ymm3, [rsi + 96]

    vmovdqu ymm4, [rsi + 128]
    vmovdqu ymm5, [rsi + 160]
    vmovdqu ymm6, [rsi + 192]
    vmovdqu ymm7, [rsi + 224]


    ; ------------------------------------------------------------
    ; Store 256B
    ; ------------------------------------------------------------

    vmovdqu [rdi],       ymm0
    vmovdqu [rdi + 32],  ymm1
    vmovdqu [rdi + 64],  ymm2
    vmovdqu [rdi + 96],  ymm3

    vmovdqu [rdi + 128], ymm4
    vmovdqu [rdi + 160], ymm5
    vmovdqu [rdi + 192], ymm6
    vmovdqu [rdi + 224], ymm7


    ; ------------------------------------------------------------
    ; Advance
    ; ------------------------------------------------------------

    add rsi, 256
    add rdi, 256
    sub rdx, 256

    ; 现在一定 rdx < 256


; ================================================================
; AVX main loop / 256 block 之后的剩余数据
;
; rdx:
;
; 0 ~ 255B
;
; 前面已经使用 YMM，
; 所以所有返回必须经过 .done_avx。
; ================================================================

.tail_after_avx:

    test rdx, rdx
    jz .done_avx


    ; ============================================================
    ; 128 ~ 255
    ; ============================================================

    cmp rdx, 128
    jae .tail128_255


    ; ============================================================
    ; 64 ~ 127
    ; ============================================================

    cmp rdx, 64
    jae .tail64_127


    ; ============================================================
    ; 32 ~ 63
    ; ============================================================

    cmp rdx, 32
    jae .tail32_63


    ; ============================================================
    ; 16 ~ 31
    ; ============================================================

    cmp rdx, 16
    jae .tail16_31


    ; ============================================================
    ; 0 ~ 15
    ; ============================================================

    jmp .tail_small15


; ================================================================
; Direct size path: 128 ~ 255B
;
; first128 + last128
;
; 注意：
; size == 128 时 first128 和 last128 完全重叠。
;
; V5 暂时保留 V4 行为，
; 避免同时修改多个变量。
; ================================================================

.size128_255:

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + 32]
    vmovdqu ymm2, [rsi + 64]
    vmovdqu ymm3, [rsi + 96]

    vmovdqu ymm4, [rsi + rdx - 128]
    vmovdqu ymm5, [rsi + rdx - 96]
    vmovdqu ymm6, [rsi + rdx - 64]
    vmovdqu ymm7, [rsi + rdx - 32]


    vmovdqu [rdi],      ymm0
    vmovdqu [rdi + 32], ymm1
    vmovdqu [rdi + 64], ymm2
    vmovdqu [rdi + 96], ymm3

    vmovdqu [rdi + rdx - 128], ymm4
    vmovdqu [rdi + rdx - 96],  ymm5
    vmovdqu [rdi + rdx - 64],  ymm6
    vmovdqu [rdi + rdx - 32],  ymm7

    vzeroupper
    ret


; ================================================================
; Direct size path: 64 ~ 127B
;
; first64 + last64
; ================================================================

.size64_127:

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + 32]

    vmovdqu ymm2, [rsi + rdx - 64]
    vmovdqu ymm3, [rsi + rdx - 32]


    vmovdqu [rdi],      ymm0
    vmovdqu [rdi + 32], ymm1

    vmovdqu [rdi + rdx - 64], ymm2
    vmovdqu [rdi + rdx - 32], ymm3

    vzeroupper
    ret


; ================================================================
; Direct size path: 32 ~ 63B
;
; first32 + last32
; ================================================================

.size32_63:

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + rdx - 32]

    vmovdqu [rdi], ymm0
    vmovdqu [rdi + rdx - 32], ymm1

    vzeroupper
    ret


; ================================================================
; Direct size path: 16 ~ 31B
;
; first16 + last16
;
; 这里只使用 VEX encoded XMM。
; ================================================================

.size16_31:

    vmovdqu xmm0, [rsi]
    vmovdqu xmm1, [rsi + rdx - 16]

    vmovdqu [rdi], xmm0
    vmovdqu [rdi + rdx - 16], xmm1

    ret


; ================================================================
; Direct size path: 0 ~ 15B
; ================================================================

.small15:

    cmp rdx, 8
    jae .size8_15

    cmp rdx, 4
    jae .size4_7

    cmp rdx, 2
    jae .size2_3

    test rdx, rdx
    jz .done_small


    ; ------------------------------------------------------------
    ; 1B
    ; ------------------------------------------------------------

    mov cl, [rsi]
    mov [rdi], cl


.done_small:

    ret


; ================================================================
; Direct size: 8 ~ 15B
; ================================================================

.size8_15:

    mov rcx, [rsi]
    mov r8, [rsi + rdx - 8]

    mov [rdi], rcx
    mov [rdi + rdx - 8], r8

    ret


; ================================================================
; Direct size: 4 ~ 7B
; ================================================================

.size4_7:

    mov ecx, [rsi]
    mov r8d, [rsi + rdx - 4]

    mov [rdi], ecx
    mov [rdi + rdx - 4], r8d

    ret


; ================================================================
; Direct size: 2 ~ 3B
; ================================================================

.size2_3:

    mov cx, [rsi]
    mov r8w, [rsi + rdx - 2]

    mov [rdi], cx
    mov [rdi + rdx - 2], r8w

    ret


; ================================================================
; AVX tail: 128 ~ 255B
;
; 与 direct .size128_255 逻辑相同，
; 但是这里必须最终经过 .done_avx。
;
; 之前想的是覆盖拷贝，虽然这样可以带来大幅的效率提升
; 但是在像 128B,384B 这类特殊的数据，在benchmark测试下会产生噪音
; 根因是 384B = 256 + 128 ，在我的逻辑下，128的数据会被复制两边
; 然后覆盖拷贝实际对于cpu来说，拷贝384的数据是拷贝来512B的数据
; ================================================================

.tail128_255:

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + 32]
    vmovdqu ymm2, [rsi + 64]
    vmovdqu ymm3, [rsi + 96]

    vmovdqu [rdi],      ymm0
    vmovdqu [rdi + 32], ymm1
    vmovdqu [rdi + 64], ymm2
    vmovdqu [rdi + 96], ymm3

    add rsi, 128
    add rdi, 128
    sub rdx, 128

    jmp .tail_after_avx

; ================================================================
; AVX tail: 64 ~ 127B
; ================================================================

.tail64_127:

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + 32]

    vmovdqu ymm2, [rsi + rdx - 64]
    vmovdqu ymm3, [rsi + rdx - 32]


    vmovdqu [rdi],      ymm0
    vmovdqu [rdi + 32], ymm1

    vmovdqu [rdi + rdx - 64], ymm2
    vmovdqu [rdi + rdx - 32], ymm3

    jmp .done_avx


; ================================================================
; AVX tail: 32 ~ 63B
; ================================================================

.tail32_63:

    vmovdqu ymm0, [rsi]
    vmovdqu ymm1, [rsi + rdx - 32]

    vmovdqu [rdi], ymm0
    vmovdqu [rdi + rdx - 32], ymm1

    jmp .done_avx


; ================================================================
; AVX tail: 16 ~ 31B
; ================================================================

.tail16_31:

    vmovdqu xmm0, [rsi]
    vmovdqu xmm1, [rsi + rdx - 16]

    vmovdqu [rdi], xmm0
    vmovdqu [rdi + rdx - 16], xmm1

    jmp .done_avx


; ================================================================
; AVX tail: 0 ~ 15B
; ================================================================

.tail_small15:

    cmp rdx, 8
    jae .tail8_15

    cmp rdx, 4
    jae .tail4_7

    cmp rdx, 2
    jae .tail2_3

    test rdx, rdx
    jz .done_avx


    ; ------------------------------------------------------------
    ; 1B
    ; ------------------------------------------------------------

    mov cl, [rsi]
    mov [rdi], cl

    jmp .done_avx


; ================================================================
; AVX tail: 8 ~ 15B
; ================================================================

.tail8_15:

    mov rcx, [rsi]
    mov r8, [rsi + rdx - 8]

    mov [rdi], rcx
    mov [rdi + rdx - 8], r8

    jmp .done_avx


; ================================================================
; AVX tail: 4 ~ 7B
; ================================================================

.tail4_7:

    mov ecx, [rsi]
    mov r8d, [rsi + rdx - 4]

    mov [rdi], ecx
    mov [rdi + rdx - 4], r8d

    jmp .done_avx


; ================================================================
; AVX tail: 2 ~ 3B
; ================================================================

.tail2_3:

    mov cx, [rsi]
    mov r8w, [rsi + rdx - 2]

    mov [rdi], cx
    mov [rdi + rdx - 2], r8w


; ================================================================
; AVX return
; ================================================================

.done_avx:

    vzeroupper
    ret


section .note.GNU-stack noalloc noexec nowrite progbits
